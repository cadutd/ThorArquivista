const assert = require("node:assert/strict");
const path = require("node:path");
const os = require("node:os");
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || "@playwright/test");
const base = process.env.BASE_URL, api = process.env.API_URL;
assert.ok(base && api && process.env.THOR_E2E_ISOLATED === "true", "Use exclusivamente a stack isolada.");
(async () => {
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:900}});
  const page = await context.newPage();
  const code = "E2E_" + Date.now();
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  let instrument, grantId;
  async function json(response) {assert.ok(response.ok(), await response.text()); return response.json();}
  try {
    await page.goto(base + "/login");
    await page.getByRole("button", {name:"Entrar em desenvolvimento"}).click();
    await page.waitForURL("**/dashboard");
    const user = await json(await context.request.get(api + "/auth/me"));
    await page.locator(".admin-navigation summary").click();
    const menu = page.locator(".admin-navigation");
    assert.equal(await menu.getByRole("link").count(), 4);
    assert.ok(!(await menu.innerText()).includes("Eventos"));
    assert.ok(!(await menu.innerText()).includes("Geral"));
    await menu.getByRole("link", {name:"Perfis",exact:true}).click();
    await page.getByRole("link", {name:"Novo perfil",exact:true}).click();
    await page.getByLabel(/^Codigo/).fill(code);
    await page.getByLabel(/^Nome/).fill("Perfil e2e administrativo");
    await page.getByLabel("Descricao", {exact:true}).fill("Perfil criado pelo teste isolado");
    await page.locator(".permission-choice").filter({has:page.getByText("instrumentos_consultar", {exact:true})}).getByRole("checkbox").check();
    const create = page.waitForResponse(r => r.url() === api + "/perfis" && r.request().method() === "POST");
    await page.getByRole("button", {name:"Salvar perfil",exact:true}).click();
    await json(await create);
    await page.waitForURL("**/perfis");
    await page.getByLabel("Busca simples", {exact:true}).fill(code);
    await page.getByLabel("Busca simples", {exact:true}).press("Enter");
    await page.getByRole("row").filter({hasText:code}).getByRole("button", {name:"Visualizar",exact:true}).click();
    const profilePopup = page.getByRole("dialog",{name:"Perfil",exact:true});
    await profilePopup.getByText(code,{exact:true}).waitFor();
    await profilePopup.getByRole("link", {name:"Editar",exact:true}).click();
    await page.waitForURL("**/perfis/" + code + "/editar");
    await page.getByLabel(/^Nome/).fill("Perfil atualizado");
    await page.getByRole("button", {name:"Salvar alteracoes",exact:true}).click();
    await page.waitForURL("**/perfis");
    instrument = await json(await context.request.post(api + "/instrumentos", {data:{nome:code,tipo:"CATALOGO"}}));
    await page.goto(base + "/usuarios");
    await page.getByLabel("Busca simples", {exact:true}).fill(user.nome);
    await page.getByLabel("Busca simples", {exact:true}).press("Enter");
    await page.getByRole("row").filter({hasText:user.nome}).getByRole("link", {name:"Editar",exact:true}).click();
    await page.waitForURL("**/usuarios/" + user.id + "/editar");
    await page.getByRole("heading",{name:"Editar usuario",exact:true}).waitFor();
    assert.equal(await page.getByRole("table").count(),0);
    await page.getByRole("link",{name:"Perfis e escopos",exact:true}).click();
    await page.waitForURL("**/usuarios/" + user.id + "/acessos");
    await page.getByRole("link", {name:"Novo acesso",exact:true}).click();
    await page.getByRole("textbox", {name:"Buscar perfil",exact:true}).fill(code);
    await page.getByRole("button", {name:"Buscar perfil",exact:true}).click();
    await page.getByLabel(/^Perfil/).selectOption(code);
    await page.getByRole("textbox", {name:"Buscar instrumento",exact:true}).fill(code);
    await page.getByRole("button", {name:"Buscar instrumento",exact:true}).click();
    await page.getByLabel(/^Instrumento/).selectOption(instrument.id);
    const grant = page.waitForResponse(r => r.url() === api + "/acessos" && r.request().method() === "POST");
    await page.getByRole("button", {name:"Salvar",exact:true}).click();
    grantId = (await json(await grant)).id;
    await page.waitForURL("**/usuarios/" + user.id + "/acessos");
    await page.getByRole("row").filter({hasText:code}).waitFor();
    page.once("dialog", d => d.accept());
    await page.getByRole("row").filter({hasText:code}).getByRole("button", {name:"Revogar acesso",exact:true}).click();
    await page.waitForFunction(() => !document.querySelector("table")?.innerText.includes("E2E_"));
    grantId = undefined;
    await page.goto(base + "/permissoes");
    await page.getByLabel("Busca simples", {exact:true}).fill("publicar");
    const search = page.waitForResponse(r => r.url().includes("/permissoes?") && r.url().includes("q=publicar"));
    await page.getByLabel("Busca simples", {exact:true}).press("Enter");
    await json(await search);
    await page.getByRole("row").filter({hasText:"Publicar"}).getByRole("button", {name:"Visualizar permissao",exact:true}).click();
    await page.getByRole("dialog", {name:"Permissao",exact:true}).waitFor();
    await page.getByRole("button", {name:"Fechar",exact:true}).click();
    await page.screenshot({path:path.join(os.tmpdir(),"thor-administracao-desktop.png")});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(os.tmpdir(),"thor-administracao-mobile.png")});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.getByRole("button", {name:"Abrir menu",exact:true}).click();
    const mobileMenu = page.getByRole("dialog", {name:"Menu",exact:true});
    assert.equal(await mobileMenu.locator(".admin-navigation").getByRole("link").count(), 4);
    await page.screenshot({path:path.join(os.tmpdir(),"thor-administracao-menu-mobile.png")});
    await mobileMenu.getByRole("link", {name:"Perfis",exact:true}).click();
    await page.waitForURL("**/perfis");
    assert.equal(await page.getByRole("dialog").count(), 0);
    await page.goto(base + "/perfis");
    await page.getByLabel("Busca simples", {exact:true}).fill(code);
    await page.getByLabel("Busca simples", {exact:true}).press("Enter");
    await page.getByRole("row").filter({hasText:code}).getByRole("button",{name:"Visualizar",exact:true}).click();
    await profilePopup.getByText(code,{exact:true}).waitFor();
    page.once("dialog", d => d.accept());
    const remove = page.waitForResponse(r => r.url() === api + "/perfis/" + code && r.request().method() === "DELETE");
    await profilePopup.getByRole("button", {name:"Excluir",exact:true}).click();
    await json(await remove);
    assert.deepEqual(errors, []);
    console.log("PASS: menu administrativo, perfil CRUD, usuario, concessao por escopo, revogacao, catalogo e desktop/mobile.");
  } finally {
    if(grantId) await context.request.delete(api + "/acessos/" + grantId);
    await context.request.delete(api + "/perfis/" + code);
    if(instrument) await context.request.delete(api + "/instrumentos/" + instrument.id);
    await browser.close();
  }
})().catch(e => {console.error(e);process.exitCode=1;});
