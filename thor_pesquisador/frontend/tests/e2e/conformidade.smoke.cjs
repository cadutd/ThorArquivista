const assert=require("node:assert/strict"),os=require("node:os"),path=require("node:path"),fs=require("node:fs");
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||"@playwright/test");
const base=process.env.BASE_URL,api=process.env.API_URL;
assert.ok(base&&api&&process.env.THOR_E2E_ISOLATED==="true","Use somente a stack isolada.");
(async()=>{
  const browser=await chromium.launch({headless:true}),context=await browser.newContext({viewport:{width:1440,height:900}});
  const page=await context.newPage(),errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  try {
    await page.goto(base+"/exportacoes");
    await page.waitForURL("**/login?next=**");
    await page.getByRole("button",{name:"Entrar em desenvolvimento"}).click();
    await page.waitForURL("**/exportacoes");
    const token=Date.now(),name="Fase5 E2E "+token;
    const response=await context.request.post(api+"/instrumentos",{data:{nome:name,tipo:"CATALOGO"}});
    assert.equal(response.status(),201);
    const instrument=(await response.json()).id;
    assert.equal((await context.request.post(api+"/instrumentos/"+instrument+"/campos",{data:{nome:"Titulo",chave:"titulo",tipo:"TEXTO_CURTO"}})).status(),201);
    assert.equal((await context.request.post(api+"/instrumentos/"+instrument+"/registros",{data:{dados:{titulo:"Exportado pelo navegador"}}})).status(),201);
    await page.goto(base+"/instrumentos/novo");await page.locator("form.panel").waitFor();
    const identity=await page.locator("form.panel").evaluate(el=>({radius:getComputedStyle(el).borderRadius,padding:getComputedStyle(el).padding,gap:getComputedStyle(el).gap,bg:getComputedStyle(el).backgroundColor}));
    await page.goto(base+"/exportacoes/nova");await page.locator("section.panel form").waitFor();
    assert.deepEqual(await page.locator("section.panel").evaluate(el=>({radius:getComputedStyle(el).borderRadius,padding:getComputedStyle(el).padding,gap:getComputedStyle(el).gap,bg:getComputedStyle(el).backgroundColor})),identity);
    await page.getByRole("button",{name:"Pesquisar instrumento",exact:true}).click();
    const lookup=page.getByRole("dialog",{name:"Pesquisar instrumento",exact:true});
    await lookup.getByLabel("Nome",{exact:true}).fill(name);
    await lookup.getByRole("button",{name:"Pesquisar",exact:true}).click();
    await lookup.getByRole("button",{name:"Selecionar "+name,exact:true}).click();
    const created=page.waitForResponse(r=>r.url()===api+"/instrumentos/"+instrument+"/exportacoes"&&r.request().method()==="POST");
    await page.getByRole("button",{name:"Solicitar exportacao",exact:true}).click();
    const job=await (await created).json();
    await page.waitForURL("**/exportacoes");
    const deadline=Date.now()+120000;
    let status;
    do {
      const result=await context.request.get(api+"/exportacoes/"+job.id);status=(await result.json()).status;
      if(status==="CONCLUIDA"||status==="FALHOU")break;
      await new Promise(r=>setTimeout(r,500));
    } while(Date.now()<deadline);
    assert.equal(status,"CONCLUIDA");
    await page.getByRole("button",{name:"Atualizar",exact:true}).click();
    await page.locator('a[title="Visualizar"][href="/exportacoes/'+job.id+'"]').click();
    await page.waitForURL("**/exportacoes/"+job.id);
    await page.locator("main").getByText(job.id,{exact:true}).waitFor();
    const downloaded=page.waitForEvent("download");
    await page.getByRole("button",{name:"Baixar arquivo",exact:true}).click();
    const file=await downloaded;
    assert.equal((JSON.parse(fs.readFileSync(await file.path(),"utf8"))).registros[0].dados.titulo,"Exportado pelo navegador");
    await page.screenshot({path:path.join(os.tmpdir(),"thor-fase5-exportacao-detail-desktop.png")});
    await page.getByRole("link",{name:"Voltar",exact:true}).click();
    await page.waitForURL("**/exportacoes");
    await page.getByRole("link",{name:"Visualizar",exact:true}).first().waitFor();
    await page.screenshot({path:path.join(os.tmpdir(),"thor-fase5-exportacoes-desktop.png")});
    await page.goto(base+"/retencao/politicas/nova");
    await page.getByLabel("Nome",{exact:false}).fill("Retencao E2E "+token);
    await page.getByRole("button",{name:"Salvar politica",exact:true}).click();await page.waitForURL("**/retencao/politicas");
    await page.getByLabel("Busca simples",{exact:true}).fill("Retencao E2E "+token);
    await page.getByRole("button",{name:"Buscar",exact:true}).click();
    const row=page.getByRole("row").filter({hasText:"Retencao E2E "+token});
    await row.getByRole("link",{name:"Retencao E2E "+token,exact:true}).click();
    await page.getByRole("heading",{name:"Retencao E2E "+token,exact:true}).waitFor();
    const policyId=page.url().split("/").pop();
    await page.getByRole("link",{name:"Editar",exact:true}).click();
    await page.waitForURL("**/retencao/politicas/"+policyId+"/editar");
    await page.getByLabel("Nome",{exact:false}).fill("Retencao E2E "+token+" editada");
    await page.getByRole("button",{name:"Salvar politica",exact:true}).click();
    await page.waitForURL("**/retencao/politicas");
    const search=page.getByLabel("Busca simples",{exact:true});
    await search.fill("Retencao E2E "+token);
    await search.press("Enter");
    await page.getByRole("link",{name:"Retencao E2E "+token+" editada",exact:true}).click();
    const requestedRetention=page.waitForResponse(r=>r.url().includes("/execucoes")&&r.request().method()==="POST");
    await page.getByRole("button",{name:"Simular",exact:true}).click();
    const retentionJob=await (await requestedRetention).json();
    await page.waitForURL("**/retencao/execucoes/"+retentionJob.id);
    const retentionDeadline=Date.now()+60000;
    let retentionStatus;
    do {
      retentionStatus=(await (await context.request.get(api+"/retencao/execucoes/"+retentionJob.id)).json()).status;
      if(["CONCLUIDA","FALHOU"].includes(retentionStatus))break;
      await new Promise(r=>setTimeout(r,500));
    } while(Date.now()<retentionDeadline);
    assert.equal(retentionStatus,"CONCLUIDA");
    await page.getByRole("button",{name:"Atualizar",exact:true}).click();
    await page.locator("main").getByText("Concluida",{exact:true}).waitFor();
    await page.goto(base+"/retencao/politicas/"+policyId);
    await page.getByRole("button",{name:"Desativar",exact:true}).click();
    const confirmation=page.getByRole("dialog",{name:"Desativar politica",exact:true});
    await confirmation.getByRole("button",{name:"Confirmar",exact:true}).click();
    await page.locator("main").getByText("Inativo",{exact:true}).waitFor();
    assert.equal(await page.getByRole("button",{name:"Simular",exact:true}).count(),0);
    await page.getByRole("link",{name:"Editar",exact:true}).click();
    await page.getByLabel("Politica ativa",{exact:true}).check();
    await page.getByRole("button",{name:"Salvar politica",exact:true}).click();
    await page.waitForURL("**/retencao/politicas");
    await page.getByRole("link",{name:"Execucoes",exact:true}).click();
    await page.waitForURL("**/retencao/execucoes");
    await page.getByRole("link",{name:"Visualizar",exact:true}).first().waitFor();
    await page.goto(base+"/auditoria");
    await page.getByRole("button",{name:"Filtros avancados",exact:true}).click();
    await page.getByLabel("Instrumento (UUID)",{exact:true}).fill(instrument);
    await page.getByRole("button",{name:"Buscar",exact:true}).click();
    await page.getByRole("link",{name:"Visualizar",exact:true}).first().click();
    await page.getByRole("heading",{name:"Evento de auditoria",exact:true}).waitFor();
    await page.locator("main pre").waitFor();
    assert.equal(await page.locator('main a[title="Editar"],main button[title="Excluir"]').count(),0);
    await page.setViewportSize({width:1440,height:600});
    await page.goto(base+"/usuarios");
    const access=page.locator(".sidebar").getByRole("link",{name:"Concessoes de acesso",exact:true});
    await access.scrollIntoViewIfNeeded();
    const bounds=await access.boundingBox();
    assert.ok(bounds.y>=0&&bounds.y+bounds.height<=600,"Menu administrativo acessivel em tela baixa");
    for(const route of ["/auditoria","/exportacoes","/retencao/politicas","/retencao/execucoes","/relatorios"]) {
      await page.goto(base+route);await page.locator("main h1").waitFor();
      if(route==="/relatorios")await page.getByRole("heading",{name:"Registros por instrumento",exact:true}).waitFor();
      else await page.getByRole("link",{name:"Visualizar",exact:true}).first().waitFor();
      await page.setViewportSize({width:390,height:844});
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),route);
      await page.screenshot({path:path.join(os.tmpdir(),"thor-fase5-"+route.replaceAll("/","-")+"-mobile.png")});
      await page.setViewportSize({width:1440,height:900});
      await page.screenshot({path:path.join(os.tmpdir(),"thor-fase5-"+route.replaceAll("/","-")+"-desktop.png")});
    }

    await page.goto(base+"/relatorios");
    await page.getByRole("heading",{name:"Registros por instrumento",exact:true}).waitFor();
    await page.getByLabel("Inicio",{exact:true}).fill("2026-02-01T00:00");
    await page.getByLabel("Fim",{exact:true}).fill("2026-01-01T00:00");
    await page.getByRole("button",{name:"Buscar",exact:true}).click();
    await page.getByRole("alert").filter({hasText:"periodo valido"}).waitFor();
    assert.equal(await page.locator("main table").count(),0,"Erro nao conserva resultados anteriores");
    await page.getByRole("button",{name:"Limpar filtros",exact:true}).click();
    await page.getByRole("heading",{name:"Registros por instrumento",exact:true}).waitFor();
    await page.route("**/auth/permissoes",route=>route.fulfill({json:{permissoes:[],escopos:{[instrument]:["auditoria_consultar"]}}}));
    await page.goto(base+"/auditoria");
    const admin=page.locator(".sidebar details.admin-navigation");
    await admin.getByRole("link",{name:"Auditoria",exact:true}).waitFor();
    assert.equal(await admin.getAttribute("open"),"");
    assert.equal(await admin.getByRole("link").count(),1,"Escopo nao libera outros modulos administrativos");
    assert.equal(await page.locator(".sidebar-nav > a[href='/auditoria']").count(),0);
    await page.setViewportSize({width:390,height:844});
    await page.getByRole("button",{name:"Abrir menu",exact:true}).click();
    const menu=page.getByRole("dialog",{name:"Menu",exact:true});
    await menu.locator("details.admin-navigation[open]").getByRole("link",{name:"Auditoria",exact:true}).waitFor();
    await menu.getByRole("button",{name:"Fechar menu",exact:true}).click();
    assert.deepEqual(errors,[]);
    console.log("PASS fase 5: menu administrativo, identidade de Instrumentos, detalhes dedicados, lookup, exportacao/download, edicao/simulacao, auditoria, relatorios e mobile.");
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
