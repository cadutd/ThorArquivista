function cpfTeste() {
  let cpf = String(Math.floor(Math.random() * 1000000000)).padStart(9,"0");
  for(const length of [9,10]) {
    let sum = 0;
    for(let i=0;i<length;i++) sum += Number(cpf[i]) * (length + 1 - i);
    const digit = sum * 10 % 11;
    cpf += String(digit === 10 ? 0 : digit);
  }
  return cpf;
}
